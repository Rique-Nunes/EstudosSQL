    id_produto   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao    VARCHAR2(100) NOT NULL,
    preco        NUMBER(10,2) NOT NULL,
    qtd_estoque  NUMBER(6) NOT NULL
);

CREATE TABLE tb_registro_vendas (
    id_venda       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto     NUMBER REFERENCES tb_prod_estoque(id_produto),
    qtd_vendida    NUMBER(6) NOT NULL,
    valor_venda    NUMBER(12,2) NOT NULL,
    data_venda     DATE DEFAULT SYSDATE NOT NULL
);

