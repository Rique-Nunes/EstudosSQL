-- Exercício 1: Sequence rotativa com CYCLE que reinicia no MINVALUE ao atingir o limite
CREATE SEQUENCE seq_ticket_diario START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 5 CYCLE CACHE 2;
SELECT seq_ticket_diario.NEXTVAL AS t1 FROM DUAL;
SELECT seq_ticket_diario.NEXTVAL AS t2 FROM DUAL;
SELECT seq_ticket_diario.NEXTVAL AS t3 FROM DUAL;
SELECT seq_ticket_diario.NEXTVAL AS t4 FROM DUAL;
