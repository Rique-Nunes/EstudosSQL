-- Exercício 1 (Justificativa): Ao atingir MAXVALUE, a cláusula CYCLE reinicia a sequência no MINVALUE sem disparar exceção ORA-08004.

-- Exercício 2: Comparação entre atribuição legada via Trigger BEFORE INSERT e a sintaxe moderna DEFAULT
CREATE TABLE tb_protocolo_legado (id_protocolo NUMBER PRIMARY KEY, assunto VARCHAR2(100) NOT NULL);
CREATE SEQUENCE seq_protocolo_legado START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER trg_protocolo_bi BEFORE INSERT ON tb_protocolo_legado FOR EACH ROW BEGIN IF :NEW.id_protocolo IS NULL THEN SELECT seq_protocolo_legado.NEXTVAL INTO :NEW.id_protocolo FROM DUAL; END IF; END;
/

