-- Exercício 1: Trigger INSTEAD OF INSERT em View complexa com JOIN para distribuição de colunas nas tabelas base
CREATE TABLE tb_departamentos (id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome_depto VARCHAR2(50) NOT NULL UNIQUE);
CREATE TABLE tb_funcionarios_depto (id_func NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_departamento NUMBER REFERENCES tb_departamentos(id_departamento), nome_func VARCHAR2(100) NOT NULL, email VARCHAR2(100) NOT NULL UNIQUE);

CREATE OR REPLACE VIEW vw_funcionarios_detalhe AS
SELECT f.id_func, f.nome_func, f.email, d.nome_depto FROM tb_funcionarios_depto f JOIN tb_departamentos d ON f.id_departamento = d.id_departamento;

CREATE OR REPLACE TRIGGER trg_vw_func_detalhe_io_insert
INSTEAD OF INSERT ON vw_funcionarios_detalhe
FOR EACH ROW
DECLARE
    v_id_depto NUMBER;
BEGIN
    BEGIN
        SELECT id_departamento INTO v_id_depto FROM tb_departamentos WHERE UPPER(nome_depto) = UPPER(:NEW.nome_depto);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO tb_departamentos (nome_depto) VALUES (UPPER(:NEW.nome_depto)) RETURNING id_departamento INTO v_id_depto;
    END;
    INSERT INTO tb_funcionarios_depto (id_departamento, nome_func, email) VALUES (v_id_depto, :NEW.nome_func, :NEW.email);
END trg_vw_func_detalhe_io_insert;
/

