-- Etapa 2: Trigger BEFORE ROW para validação de piso e impedimento de redução salarial
CREATE OR REPLACE TRIGGER trg_empregados_biu_valida
BEFORE INSERT OR UPDATE ON tb_empregados
FOR EACH ROW
BEGIN
    :NEW.nome  := UPPER(TRIM(:NEW.nome));
    :NEW.cargo := UPPER(TRIM(:NEW.cargo));
    IF :NEW.salario < 1412.00 THEN RAISE_APPLICATION_ERROR(-20001, 'Salário inferior ao piso.'); END IF;
    IF UPDATING AND :NEW.salario < :OLD.salario THEN RAISE_APPLICATION_ERROR(-20002, 'Não é permitida redução salarial.'); END IF;
END trg_empregados_biu_valida;
/

-- Etapa 3: Trigger AFTER ROW para gravação de histórico de alterações salariais
CREATE OR REPLACE TRIGGER trg_empregados_auditoria
AFTER INSERT OR UPDATE OR DELETE ON tb_empregados
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo) VALUES (:NEW.id_empregado, 'INSERT', NULL, :NEW.salario);
    ELSIF UPDATING AND :NEW.salario <> :OLD.salario THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo) VALUES (:OLD.id_empregado, 'UPDATE', :OLD.salario, :NEW.salario);
    ELSIF DELETING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo) VALUES (:OLD.id_empregado, 'DELETE', :OLD.salario, NULL);
    END IF;
END trg_empregados_auditoria;
/

-- Etapa 4: Trigger BEFORE STATEMENT para bloquear operações de exclusão aos finais de semana
CREATE OR REPLACE TRIGGER trg_bloqueio_fim_semana
BEFORE DELETE ON tb_empregados
DECLARE
    v_dia VARCHAR2(20);
BEGIN
    v_dia := TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');
    IF v_dia IN ('SAT', 'SUN') THEN RAISE_APPLICATION_ERROR(-20005, 'Exclusões proibidas no fim de semana.'); END IF;
END trg_bloqueio_fim_semana;
/

