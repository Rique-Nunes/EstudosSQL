-- Exercício 1: Tipo t_retangulo com cálculo de área e perímetro via Member Functions
CREATE OR REPLACE TYPE t_retangulo AS OBJECT (
    largura NUMBER,
    altura  NUMBER,
    MEMBER FUNCTION calcular_area RETURN NUMBER,
    MEMBER FUNCTION calcular_perimetro RETURN NUMBER
);
/

CREATE OR REPLACE TYPE BODY t_retangulo AS
    MEMBER FUNCTION calcular_area RETURN NUMBER IS BEGIN RETURN largura * altura; END;
    MEMBER FUNCTION calcular_perimetro RETURN NUMBER IS BEGIN RETURN 2 * (largura + altura); END;
END;
/

DECLARE
    v_ret t_retangulo := t_retangulo(10, 5);
BEGIN
    DBMS_OUTPUT.PUT_LINE('Área: ' || v_ret.calcular_area() || ' | Perímetro: ' || v_ret.calcular_perimetro());
END;
/

-- Exercício 2: Tipo t_retangulo_ordenavel com método MAP para ordenação por área em consultas SQL
CREATE OR REPLACE TYPE t_retangulo_ordenavel AS OBJECT (
    largura NUMBER,
    altura  NUMBER,
    MEMBER FUNCTION calcular_area RETURN NUMBER,
    MEMBER FUNCTION calcular_perimetro RETURN NUMBER,
    MAP MEMBER FUNCTION ordenar RETURN NUMBER
);
/

CREATE OR REPLACE TYPE BODY t_retangulo_ordenavel AS
    MEMBER FUNCTION calcular_area RETURN NUMBER IS BEGIN RETURN largura * altura; END;
    MEMBER FUNCTION calcular_perimetro RETURN NUMBER IS BEGIN RETURN 2 * (largura + altura); END;
    MAP MEMBER FUNCTION ordenar RETURN NUMBER IS BEGIN RETURN largura * altura; END;
END;
/

