-- Exercício 1: Criação da MV mv_vendas_categoria com Complete Refresh
CREATE MATERIALIZED VIEW mv_vendas_categoria
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
ENABLE QUERY REWRITE
AS
SELECT 
    p.categoria,
    COUNT(*) AS total_transacoes,
    SUM(v.quantidade) AS qtd_total_vendida,
    SUM(v.valor_total) AS faturamento_total
FROM tb_vendas v
JOIN tb_produtos p ON v.id_produto = p.id_produto
GROUP BY p.categoria;

SELECT * FROM mv_vendas_categoria ORDER BY faturamento_total DESC;

BEGIN
    DBMS_MVIEW.REFRESH(LIST => 'MV_VENDAS_CATEGORIA', METHOD => 'C');
END;
/

