CREATE UNIQUE INDEX idx_func_matricula ON tb_funcionarios(matricula);
SELECT id_funcionario, nome, departamento, salario FROM tb_funcionarios WHERE matricula = 'MAT-005420';

-- Etapa 4: Criação de Function-Based Index na coluna UPPER(nome)
SELECT matricula, nome, cargo, salario FROM tb_funcionarios WHERE UPPER(nome) = 'FUNCIONARIO 2500';
CREATE INDEX idx_func_nome_upper ON tb_funcionarios(UPPER(nome));
SELECT matricula, nome, cargo, salario FROM tb_funcionarios WHERE UPPER(nome) = 'FUNCIONARIO 2500';

-- Etapa 5: Criação de índice composto e consulta com cobertura total (Index-Only Scan)
CREATE INDEX idx_func_dep_cargo_sal ON tb_funcionarios(departamento, cargo, salario);
SELECT cargo, salario FROM tb_funcionarios WHERE departamento = 'TI' AND cargo = 'ANALISTA';

