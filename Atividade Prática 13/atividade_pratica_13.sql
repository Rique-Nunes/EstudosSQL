-- Etapa 2: Função determinística fnc_calcular_irrf para cálculo progressivo de imposto
CREATE OR REPLACE FUNCTION fnc_calcular_irrf (p_salario_bruto IN NUMBER) RETURN NUMBER DETERMINISTIC IS
    v_imposto NUMBER(10,2) := 0;
BEGIN
    IF p_salario_bruto IS NULL OR p_salario_bruto <= 2259.20 THEN v_imposto := 0;
    ELSIF p_salario_bruto <= 2826.65 THEN v_imposto := (p_salario_bruto * 0.075) - 169.44;
    ELSIF p_salario_bruto <= 3751.05 THEN v_imposto := (p_salario_bruto * 0.15) - 381.44;
    ELSIF p_salario_bruto <= 4664.68 THEN v_imposto := (p_salario_bruto * 0.225) - 662.77;
    ELSE v_imposto := (p_salario_bruto * 0.275) - 896.00;
    END IF;
    RETURN ROUND(GREATEST(v_imposto, 0), 2);
END fnc_calcular_irrf;
/

-- Etapa 3: Função fnc_obter_comissao com consulta SQL e escala progressiva de comissão
CREATE OR REPLACE FUNCTION fnc_obter_comissao (p_id_colaborador IN NUMBER, p_mes_ano IN VARCHAR2) RETURN NUMBER IS
    v_total_vendas NUMBER(12,2) := 0;
    v_percentual   NUMBER(5,4) := 0;
BEGIN
    SELECT NVL(SUM(total_vendido), 0) INTO v_total_vendas FROM tb_vendas_colaborador WHERE id_colaborador = p_id_colaborador AND mes_ano = p_mes_ano;
    IF v_total_vendas >= 100000.00 THEN v_percentual := 0.05;
    ELSIF v_total_vendas >= 50000.00 THEN v_percentual := 0.035;
    ELSIF v_total_vendas > 0 THEN v_percentual := 0.02;
    ELSE v_percentual := 0;
    END IF;
    RETURN ROUND(v_total_vendas * v_percentual, 2);
END fnc_obter_comissao;
/

