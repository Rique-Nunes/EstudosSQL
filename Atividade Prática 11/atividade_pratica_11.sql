-- Etapa 2: Criação de sinônimo privado para simplificação e abstração de schema
CREATE OR REPLACE SYNONYM clientes FOR tb_cad_clientes_corp_nacional;
SELECT id_cliente, codigo_empresa, razao_social, cidade, limite_credito FROM clientes WHERE status_conta = 'ATIVO';

-- Etapa 3: Operações DML transparentes executadas através do sinônimo
INSERT INTO clientes (codigo_empresa, razao_social, cidade, limite_credito, status_conta)
VALUES ('CORP-004', 'Distribuidora Farmacêutica Rio', 'Niterói', 320000.00, 'ATIVO');
