SELECT codigo_empresa, razao_social, limite_credito FROM clientes WHERE codigo_empresa = 'CORP-004';
SELECT codigo_empresa, razao_social, limite_credito FROM tb_cad_clientes_corp_nacional WHERE codigo_empresa = 'CORP-004';

-- Etapa 4: Abstração de sequence através de sinônimo
CREATE SEQUENCE seq_tb_cad_clientes_corp_id START WITH 500 INCREMENT BY 1 NOCACHE;
CREATE OR REPLACE SYNONYM seq_clientes FOR seq_tb_cad_clientes_corp_id;
SELECT seq_clientes.NEXTVAL AS proximo_id FROM DUAL;
SELECT seq_clientes.CURRVAL AS id_atual FROM DUAL;

-- Etapa 5: Refatoração transparente apontando o sinônimo para uma View sem alterar a aplicação
CREATE OR REPLACE VIEW vw_clientes_ativos AS
SELECT id_cliente, codigo_empresa, razao_social, cidade, limite_credito
FROM tb_cad_clientes_corp_nacional WHERE status_conta = 'ATIVO';

CREATE OR REPLACE SYNONYM clientes FOR vw_clientes_ativos;
SELECT * FROM clientes;

-- Etapa 6: Consulta de metadados em USER_SYNONYMS
SELECT synonym_name, table_owner, table_name, db_link FROM user_synonyms ORDER BY synonym_name;

