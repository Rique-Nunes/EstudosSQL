-- Exercício 3: Procedure prc_sanitizar_texto com parâmetro IN OUT para aplicar TRIM e UPPER
CREATE OR REPLACE PROCEDURE prc_sanitizar_texto (p_texto IN OUT VARCHAR2) IS
BEGIN
    IF p_texto IS NOT NULL THEN p_texto := UPPER(TRIM(p_texto)); END IF;
END prc_sanitizar_texto;
/

DECLARE
    v_str VARCHAR2(50) := '  teste texto  ';
BEGIN
    prc_sanitizar_texto(v_str);
    DBMS_OUTPUT.PUT_LINE('Resultado: [' || v_str || ']');
END;
/
