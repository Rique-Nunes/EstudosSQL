-- Exercício 1: Procedure prc_reajustar_saldo_em_massa que atualiza contas ativas e retorna SQL%ROWCOUNT
CREATE OR REPLACE PROCEDURE prc_reajustar_saldo_em_massa (
    p_percentual       IN  NUMBER,
    p_total_atualizado OUT NUMBER
) IS
BEGIN
    UPDATE tb_contas SET saldo = ROUND(saldo * (1 + (p_percentual / 100)), 2) WHERE status = 'ATIVA';
    p_total_atualizado := SQL%ROWCOUNT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN ROLLBACK; p_total_atualizado := 0; RAISE;
END prc_reajustar_saldo_em_massa;
/

DECLARE
    v_total NUMBER;
BEGIN
    prc_reajustar_saldo_em_massa(5.0, v_total);
    DBMS_OUTPUT.PUT_LINE('Contas atualizadas: ' || v_total);
END;
/

