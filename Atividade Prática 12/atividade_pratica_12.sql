-- Etapa 2: Procedure prc_realizar_deposito com parâmetros IN e OUT
CREATE OR REPLACE PROCEDURE prc_realizar_deposito (
    p_id_conta    IN  NUMBER,
    p_valor       IN  NUMBER,
    p_novo_saldo  OUT NUMBER,
    p_status_msg  OUT VARCHAR2
) IS
    v_status_conta VARCHAR2(10);
BEGIN
    IF p_valor <= 0 THEN
        p_status_msg := 'ERRO: O valor do depósito deve ser maior que zero.';
        p_novo_saldo := NULL;
        RETURN;
    END IF;

    SELECT status, saldo INTO v_status_conta, p_novo_saldo FROM tb_contas WHERE id_conta = p_id_conta;

    IF v_status_conta <> 'ATIVA' THEN
        p_status_msg := 'ERRO: A conta está bloqueada ou inativa.';
        p_novo_saldo := NULL;
        RETURN;
    END IF;

    UPDATE tb_contas SET saldo = saldo + p_valor WHERE id_conta = p_id_conta RETURNING saldo INTO p_novo_saldo;
    INSERT INTO tb_movimentacoes (id_conta_dest, tipo_operacao, valor) VALUES (p_id_conta, 'DEPOSITO', p_valor);
    COMMIT;
    p_status_msg := 'SUCESSO: Depósito efetuado com êxito.';
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_status_msg := 'ERRO: Conta inexistente.';
        p_novo_saldo := NULL;
        ROLLBACK;
    WHEN OTHERS THEN
        p_status_msg := 'ERRO INESPERADO: ' || SQLERRM;
        p_novo_saldo := NULL;
        ROLLBACK;
END prc_realizar_deposito;
/

-- Etapa 3: Chamada de procedure via bloco anônimo PL/SQL com DBMS_OUTPUT
DECLARE
    v_saldo_atual NUMBER;
    v_mensagem    VARCHAR2(200);
BEGIN
    prc_realizar_deposito(p_id_conta => 1, p_valor => 1500.00, p_novo_saldo => v_saldo_atual, p_status_msg => v_mensagem);
    DBMS_OUTPUT.PUT_LINE(v_mensagem || ' | Novo Saldo: R$ ' || v_saldo_atual);
END;
/

-- Etapa 4: Procedure prc_transferir_fundos com bloqueio FOR UPDATE e controle transacional
CREATE OR REPLACE PROCEDURE prc_transferir_fundos (
    p_origem  IN NUMBER,
    p_destino IN NUMBER,
    p_valor   IN NUMBER
) IS
    v_saldo_origem NUMBER;
    v_status_orig  VARCHAR2(10);
    v_status_dest  VARCHAR2(10);
    e_saldo_insuficiente EXCEPTION;
    e_conta_bloqueada    EXCEPTION;
BEGIN
    IF p_valor <= 0 THEN RAISE_APPLICATION_ERROR(-20001, 'Valor de transferência inválido.'); END IF;

    SELECT saldo, status INTO v_saldo_origem, v_status_orig FROM tb_contas WHERE id_conta = p_origem FOR UPDATE;
    IF v_status_orig <> 'ATIVA' THEN RAISE e_conta_bloqueada; END IF;
    IF v_saldo_origem < p_valor THEN RAISE e_saldo_insuficiente; END IF;

    SELECT status INTO v_status_dest FROM tb_contas WHERE id_conta = p_destino;
    IF v_status_dest <> 'ATIVA' THEN RAISE e_conta_bloqueada; END IF;

    UPDATE tb_contas SET saldo = saldo - p_valor WHERE id_conta = p_origem;
    UPDATE tb_contas SET saldo = saldo + p_valor WHERE id_conta = p_destino;
    INSERT INTO tb_movimentacoes (id_conta_origem, id_conta_dest, tipo_operacao, valor) VALUES (p_origem, p_destino, 'TRANSFERENCIA', p_valor);
    COMMIT;
EXCEPTION
    WHEN e_saldo_insuficiente THEN ROLLBACK; RAISE_APPLICATION_ERROR(-20002, 'Falha: Saldo insuficiente.');
    WHEN e_conta_bloqueada THEN ROLLBACK; RAISE_APPLICATION_ERROR(-20003, 'Falha: Conta bloqueada.');
    WHEN NO_DATA_FOUND THEN ROLLBACK; RAISE_APPLICATION_ERROR(-20004, 'Falha: Conta não localizada.');
    WHEN OTHERS THEN ROLLBACK; RAISE_APPLICATION_ERROR(-20099, 'Erro: ' || SQLERRM);
END prc_transferir_fundos;
/

