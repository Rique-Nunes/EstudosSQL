-- Etapa 1: Criação do esquema base de contas correntes e movimentações
CREATE TABLE tb_contas (
    id_conta     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titular      VARCHAR2(100) NOT NULL,
    saldo        NUMBER(12,2) DEFAULT 0 NOT NULL,
    status       VARCHAR2(10) DEFAULT 'ATIVA' CHECK (status IN ('ATIVA', 'BLOQUEADA'))
);

CREATE TABLE tb_movimentacoes (
    id_movimento    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta_origem NUMBER REFERENCES tb_contas(id_conta),
    id_conta_dest   NUMBER REFERENCES tb_contas(id_conta),
    tipo_operacao   VARCHAR2(20) NOT NULL,
    valor           NUMBER(12,2) NOT NULL,
    data_movimento  DATE DEFAULT SYSDATE NOT NULL
);

